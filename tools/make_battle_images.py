"""Embeds the card battle's pictures from the three.js version into src/starting_template/st_battle_images.c:
the 12 location pictures (static/zones/*.jpg, made smaller) and the 3 battle backgrounds (static/backgrounds/*.png).
They are decoded at run time (image_decode_rgba8), the first time a battle is drawn.

Run from the project root:  python tools/make_battle_images.py [path to the three.js project]
"""
import io
import os
import sys

from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else r'C:\dev\pokemonsnap'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'starting_template', 'st_battle_images.c')
# ZoneId order (st_cards.c)
ZONES = ['meadow', 'stage', 'pond', 'grove', 'ledge', 'barn', 'library', 'gym', 'toybox', 'clock', 'tower', 'workshop']
BACKS = ['forest', 'cave', 'lab']  # BattleKind: wild, rival, practice


def c_bytes(name, data):
    rows = [', '.join(str(b) for b in data[i:i + 40]) for i in range(0, len(data), 40)]
    return f'static const u8 {name}[{len(data)}] = {{\n' + ',\n'.join(rows) + '};\n'


parts = ['// Generated by tools/make_battle_images.py from the three.js version: do not edit.\n'
         '// The location pictures (JPEG, 400x225) and the battle backgrounds (PNG pixel art).\n\n']
zone_names, back_names = [], []
for z in ZONES:
    im = Image.open(os.path.join(SRC, 'static', 'zones', z + '.jpg')).convert('RGB').resize((400, 225), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, 'JPEG', quality=78, optimize=True)
    parts.append(c_bytes(f'zone_img_{z}', buf.getvalue()))
    zone_names.append(f'zone_img_{z}')
for b in BACKS:
    with open(os.path.join(SRC, 'static', 'backgrounds', b + '.png'), 'rb') as f:
        data = f.read()
    parts.append(c_bytes(f'back_img_{b}', data))
    back_names.append(f'back_img_{b}')
parts.append('\ntypedef struct EmbeddedImage {\n  const u8 *data;\n  u32 len;\n} EmbeddedImage;\n\n')
parts.append('static const EmbeddedImage ZONE_IMAGES[] = {' + ', '.join(f'{{{n}, sizeof({n})}}' for n in zone_names) + '};\n')
parts.append('static const EmbeddedImage BACK_IMAGES[] = {' + ', '.join(f'{{{n}, sizeof({n})}}' for n in back_names) + '};\n')
with open(OUT, 'w', newline='\n') as f:
    f.write(''.join(parts))
print(f'wrote {OUT} ({os.path.getsize(OUT) // 1024} KB)')
