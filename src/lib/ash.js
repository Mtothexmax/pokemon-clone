/**
 * Stride frame: shift left leg/shoe span one px left, right span one px
 * right (snapshot first, zero-fill). Spans must stay in-bounds and disjoint.
 */
export function stride(m, groups) {
	const out = m.map((r) => r.slice());
	for (const { rows, l0, l1, r0, r1 } of groups) {
		for (const y of rows) {
			const L = m[y].slice(l0, l1 + 1);
			const R = m[y].slice(r0, r1 + 1);
			for (let x = l0; x <= l1; x++) out[y][x] = 0;
			for (let x = r0; x <= r1; x++) out[y][x] = 0;
			L.forEach((v, i) => {
				out[y][l0 - 1 + i] = v;
			});
			R.forEach((v, i) => {
				out[y][r0 + 1 + i] = v;
			});
		}
	}
	return out;
}

/** Back view from the front matrix: face->hair, jacket center->backpack. */
export function backView(m) {
	const out = m.map((r) => r.slice());
	const fill = (y0, y1, x0, x1, v) => {
		for (let y = y0; y <= y1; y++)
			for (let x = x0; x <= x1; x++) if (out[y][x] !== 1) out[y][x] = v;
	};
	fill(8, 12, 8, 21, 6);
	fill(13, 13, 9, 20, 6);
	fill(15, 19, 8, 20, 8);
	return out;
}

const range = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => a + i);
const DOWN_GROUPS = [{ rows: range(23, 29), l0: 8, l1: 12, r0: 15, r1: 20 }];
const SIDE_GROUPS = [
	{ rows: range(23, 26), l0: 10, l1: 13, r0: 16, r1: 19 },
	{ rows: [27, 28], l0: 8, l1: 14, r0: 14, r1: 21 },
	{ rows: [29], l0: 9, l1: 12, r0: 15, r1: 20 }
];

/** All player frames: down/up/side x stand/stride. */
export function buildAshFrames() {
	const back = backView(ASH_DOWN);
	return {
		down: [ASH_DOWN, stride(ASH_DOWN, DOWN_GROUPS)],
		up: [back, stride(back, DOWN_GROUPS)],
		side: [ASH_SIDE, stride(ASH_SIDE, SIDE_GROUPS)]
	};
}
